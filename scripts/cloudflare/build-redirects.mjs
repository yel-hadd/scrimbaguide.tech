#!/usr/bin/env node

/**
 * Write build/_redirects for Cloudflare Workers static assets.
 *
 * Two kinds of line, all 301 and all static:
 * - every client-redirect stub (a build/<route>/index.html whose meta refresh
 *   points elsewhere) becomes a real 301 from both `/<route>` and `/<route>/`
 *   to its final target, following stub chains;
 * - every real page gets `/<route> /<route>/ 301`, because Workers'
 *   html_handling adds the trailing slash with a 307, and GitHub Pages
 *   (and Google's view of these URLs) used a 301.
 *
 * _redirects runs before asset matching, so the stubs stay in the build only
 * as a fallback. Cloudflare allows 2,000 static redirects; we fail above
 * MAX_LINES to leave headroom.
 *
 * Usage: node scripts/cloudflare/build-redirects.mjs [--build build]
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MAX_LINES = 1900;
const MAX_CHAIN = 10;

const REFRESH_RE = /<meta[^>]+http-equiv=["']refresh["'][^>]*content=["'][^"']*url=([^"']+)["']/i;

/** Route (`/a/b/`) for build/a/b/index.html, or null for non-index files. */
export function routeForFile(buildDir, file) {
  const rel = path.relative(buildDir, file).split(path.sep).join('/');
  if (rel === 'index.html') return '/';
  if (!rel.endsWith('/index.html')) return null;
  return `/${rel.slice(0, -'index.html'.length)}`;
}

/** Meta-refresh target of a stub page, resolved against its route; null for real pages. */
export function stubTarget(html, route) {
  const m = REFRESH_RE.exec(html);
  if (!m) return null;
  const url = new URL(m[1].trim(), `https://x${route}`);
  if (url.origin !== 'https://x') return url.href;
  return url.pathname + url.search + url.hash;
}

/** Ensure a site-relative path ends in `/` (files with an extension are left alone). */
export function withSlash(target) {
  if (!target.startsWith('/')) return target;
  const [, p, rest] = /^([^?#]*)(.*)$/.exec(target);
  if (p.endsWith('/') || /\.[a-z0-9]+$/i.test(p)) return p + rest;
  return `${p}/${rest}`;
}

/**
 * @param {Map<string, string|null>} routes route -> stub target (null = real page)
 * @returns {string[]} _redirects lines
 */
export function buildRedirectLines(routes) {
  const resolve = (route) => {
    let target = routes.get(route);
    for (let i = 0; i < MAX_CHAIN; i++) {
      const next = withSlash(target);
      const nextStub = routes.get(next);
      if (!nextStub) return next;
      target = nextStub;
    }
    throw new Error(`redirect chain longer than ${MAX_CHAIN} from ${route}`);
  };

  const stubs = [];
  const pages = [];
  for (const route of [...routes.keys()].sort()) {
    if (route === '/') continue;
    const bare = route.slice(0, -1);
    if (routes.get(route)) {
      const to = resolve(route);
      if (to === route) throw new Error(`stub ${route} redirects to itself`);
      stubs.push(`${bare} ${to} 301`, `${route} ${to} 301`);
    } else {
      pages.push(`${bare} ${route} 301`);
    }
  }
  return [...stubs, ...pages];
}

export function collectRoutes(buildDir) {
  const routes = new Map();
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name === 'index.html') {
        const route = routeForFile(buildDir, full);
        routes.set(route, stubTarget(fs.readFileSync(full, 'utf8'), route));
      }
    }
  };
  walk(buildDir);
  return routes;
}

function main() {
  const args = process.argv.slice(2);
  const i = args.indexOf('--build');
  const __dirname = path.dirname(fileURLToPath(import.meta.url));
  const buildDir = path.resolve(i !== -1 ? args[i + 1] : path.join(__dirname, '..', '..', 'build'));

  const routes = collectRoutes(buildDir);
  const lines = buildRedirectLines(routes);
  if (lines.length > MAX_LINES) {
    console.error(`_redirects has ${lines.length} lines; the limit we allow is ${MAX_LINES} (Cloudflare: 2,000 static).`);
    process.exit(1);
  }
  const header = '# Generated by scripts/cloudflare/build-redirects.mjs. Do not edit.\n';
  fs.writeFileSync(path.join(buildDir, '_redirects'), header + lines.join('\n') + '\n');
  const stubCount = [...routes.values()].filter(Boolean).length;
  console.log(`_redirects: ${lines.length} lines (${stubCount} stubs, ${routes.size - stubCount - 1} pages)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main();
