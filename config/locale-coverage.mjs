/**
 * Per-locale content exclusion: the one place that answers "does THIS locale
 * build THIS file / route / sidebar entry".
 *
 * I18N-PLAN.md section 4 Phase 2 tasks (a), (c) and (d). A Core-set locale must
 * genuinely not build the ~170 pages it has not translated, and naively
 * excluding them breaks the build in four independent places, none of which is
 * recoverable at runtime. Those four places live in three different languages
 * (a TS sidebar, a TS config, an .mjs prebuild script), so the rule that decides
 * coverage is written ONCE here, in .mjs, and imported by all of them:
 *
 *   sidebars.ts                  -> filterSidebars()      (task a)
 *   docusaurus.config.ts         -> contentExcludeOption() (task d)
 *   config/navigation.ts         -> coverage.unrestricted  (task d, footer legal)
 *   scripts/prune-locale-links.mjs -> localeCoverage()     (task c)
 *
 * It is .mjs rather than .ts on purpose: jiti loads it fine from the TS config
 * modules (verified), while `node --test` can import it directly. A .ts copy
 * would be untestable without a compile step, and a second copy of a
 * fail-closed rule is how the two copies drift into disagreeing.
 *
 * FAIL-CLOSED IS THE WHOLE POINT
 * ------------------------------
 * A locale absent from `i18n/coverage.json`, or present with zero entries,
 * excludes ALL docs/blog content. Failing open would publish English fallback
 * under a non-English hreflang, which is exactly the invariant-4 violation
 * Phase 2 exists to prevent, and it would do so with a green build.
 *
 * The default locale is the ONE exception, and it is not really an exception:
 * `en` is the translation SOURCE, `build-coverage-manifest.mjs` deliberately
 * skips it, so its absence from the manifest carries no information. English is
 * therefore unrestricted, which is what keeps `make dev` and the English build
 * byte-identical to before this file existed.
 *
 * Single escape hatch: `I18N_COVERAGE=full` bypasses exclusion entirely, for
 * local RTL and typography QA only (section 4 Phase 4). `deploy.yml` fails if it
 * is set.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSourceUniverse, loadRoster } from '../scripts/build-coverage-manifest.mjs';

/**
 * `GlobExcludeDefault` from `@docusaurus/utils`, inlined.
 *
 * Setting `exclude` REPLACES the plugin default instead of extending it, so
 * these have to be restated or `_partial.mdx` files start being built as pages.
 * They are copied rather than imported because `@docusaurus/utils` is a
 * transitive dependency this repo does not declare, and a config-load-time
 * import of an undeclared package fails the build for every locale. The test
 * suite imports the real constant and pins this copy against it, so drift shows
 * up as a failing test instead of a mis-built site.
 */
const GLOB_EXCLUDE_DEFAULT = [
  '**/_*.{js,jsx,ts,tsx,md,mdx}',
  '**/_*/**',
  '**/*.test.{js,jsx,ts,tsx}',
  '**/__tests__/**',
];

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Mirrored from `i18n/locales.config.ts`, which is TypeScript and cannot be
 * imported here without a compile step. `scripts/__tests__/prune-locale-links.test.mjs`
 * pins this against the roster, so a change there fails a test rather than
 * silently un-restricting the wrong locale.
 */
export const DEFAULT_LOCALE = 'en';

/** Content surfaces that carry a locale-excludable markdown file on disk. */
export const SURFACES = ['docs', 'blog', 'pages'];

/**
 * The current build locale, resolved SAFELY.
 *
 * `start.js` does `process.env.DOCUSAURUS_CURRENT_LOCALE = cliOptions.locale`
 * unconditionally, so a bare `docusaurus start` stores the literal string
 * "undefined". Both `?? DEFAULT_LOCALE` and `|| DEFAULT_LOCALE` happily return
 * that string, which then misses every manifest lookup and (fail-closed) would
 * exclude the entire site during local development. Hence the explicit
 * sentinel check rather than the idiomatic one.
 */
export function resolveCurrentLocale(env = process.env) {
  const raw = env?.DOCUSAURUS_CURRENT_LOCALE;
  if (typeof raw !== 'string') return DEFAULT_LOCALE;
  const trimmed = raw.trim();
  if (trimmed === '' || trimmed === 'undefined' || trimmed === 'null') return DEFAULT_LOCALE;
  return trimmed;
}

/** The one escape hatch. Local RTL/typography QA only; CI rejects it. */
export function isCoverageBypassed(env = process.env) {
  return env?.I18N_COVERAGE === 'full';
}

/**
 * Read the generated manifest. Missing file -> null, which for a non-default
 * locale means "no coverage at all" and NOT "build everything".
 *
 * A malformed manifest throws instead of degrading: it is generated by
 * `prebuild`, so corruption is a broken pipeline, and guessing at that point
 * would be guessing about which pages get an hreflang annotation.
 */
export function loadCoverageManifest(root = ROOT) {
  const file = path.join(root, 'i18n', 'coverage.json');
  let raw;
  try {
    raw = fs.readFileSync(file, 'utf8');
  } catch (error) {
    if (error?.code === 'ENOENT') return null;
    throw error;
  }
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(
      `i18n/coverage.json is present but unparseable (${error.message}). ` +
      `Delete it and re-run \`node scripts/build-coverage-manifest.mjs\`.`,
    );
  }
}

/** Hand-authored declared scope, read for its alwaysExcluded / alwaysBuilt lists. */
export function loadTiers(root = ROOT) {
  return JSON.parse(fs.readFileSync(path.join(root, 'i18n', 'tiers.json'), 'utf8'));
}

/**
 * Every locale tag in the roster except the default one, i.e. every path prefix
 * a URL in this repo may legitimately carry. Parsed from the roster rather than
 * restated, for the same reason `src/utils/localePath.ts` refuses a
 * `/^\/[a-z]{2}\//` regex: a pattern that looks right would also eat a
 * two-letter top-level route.
 */
let prefixCache = null;
export function localePrefixes() {
  if (!prefixCache) {
    prefixCache = new Set(loadRoster().map((r) => r.locale).filter((l) => l !== DEFAULT_LOCALE));
  }
  return prefixCache;
}

/** Canonical manifest key for a site path: locale-free, leading and trailing slash, no hash or query. */
export function toManifestRoute(target) {
  if (typeof target !== 'string' || !target.startsWith('/')) return null;
  const clean = target.split('#')[0].split('?')[0];
  const segments = clean.split('/').filter(Boolean);
  if (segments.length && localePrefixes().has(segments[0])) segments.shift();
  return segments.length ? `/${segments.join('/')}/` : '/';
}

/** Doc id for a docs source file. Docusaurus derives it as the path minus extension. */
export function docIdForSourceFile(sourceFile) {
  return sourceFile.replace(/\.mdx?$/, '');
}

/**
 * Globby treats these as pattern syntax, so a filename containing one would be
 * excluded partially or not at all. That failure is silent and it fails OPEN
 * (the page builds untranslated), so it throws instead.
 */
const GLOB_META = /[*?[\]{}()!+@|]/;
function assertGlobSafe(file) {
  if (GLOB_META.test(file)) {
    throw new Error(
      `Source file '${file}' contains glob metacharacters, so it cannot be used ` +
      `verbatim as a plugin \`exclude\` pattern. Rename the file.`,
    );
  }
  return file;
}

/**
 * What one locale builds.
 *
 * `unrestricted: true` means "apply no filtering anywhere". Consumers must
 * branch on it rather than on the (deliberately empty) sets, because empty sets
 * mean the opposite thing: nothing covered.
 */
export function localeCoverage({
  locale = resolveCurrentLocale(),
  env = process.env,
  root = ROOT,
  manifest,
  universe,
} = {}) {
  if (isCoverageBypassed(env)) {
    return unrestrictedCoverage(locale, 'I18N_COVERAGE=full');
  }
  if (locale === DEFAULT_LOCALE) {
    return unrestrictedCoverage(locale, 'default locale is the translation source');
  }

  const resolvedManifest = manifest ?? loadCoverageManifest(root);
  const entries = resolvedManifest?.locales?.[locale]?.entries ?? [];

  const routes = new Set();
  const covered = { docs: new Set(), blog: new Set(), pages: new Set() };
  for (const entry of entries) {
    if (entry?.route) routes.add(entry.route);
    // alwaysBuilt entries are .tsx routes with no markdown source; they are not
    // excludable and must not be mistaken for a covered markdown file.
    if (entry?.sourceFile && covered[entry.surface]) covered[entry.surface].add(entry.sourceFile);
  }

  const resolvedUniverse = universe ?? buildSourceUniverse();
  const uncovered = { docs: [], blog: [], pages: [] };
  for (const entry of resolvedUniverse) {
    if (!uncovered[entry.surface]) continue;
    if (covered[entry.surface].has(entry.sourceFile)) continue;
    uncovered[entry.surface].push(entry.sourceFile);
  }

  return {
    locale,
    unrestricted: false,
    reason: entries.length ? 'manifest' : 'manifest miss: excluding all translated content',
    routes,
    docIds: new Set([...covered.docs].map(docIdForSourceFile)),
    covered,
    uncovered,
  };
}

function unrestrictedCoverage(locale, reason) {
  return {
    locale,
    unrestricted: true,
    reason,
    routes: new Set(),
    docIds: new Set(),
    covered: { docs: new Set(), blog: new Set(), pages: new Set() },
    uncovered: { docs: [], blog: [], pages: [] },
  };
}

let currentCache = null;
/** Memoized coverage for this process. Config and sidebars must agree, and both load per build. */
export function currentLocaleCoverage(options) {
  if (options) return localeCoverage(options);
  if (!currentCache) currentCache = localeCoverage();
  return currentCache;
}

/**
 * The `exclude` option for one content plugin, or `undefined` when the key
 * should be omitted entirely.
 *
 * Omitting it for English matters: `exclude` REPLACES the plugin default rather
 * than extending it, so writing even an equivalent array here would be a change
 * to the English build for no reason. When a locale does restrict, the default
 * patterns are re-added explicitly, or partials (`_*.mdx`) would start being
 * treated as pages.
 *
 * The patterns are FILE-PATH globs relative to the plugin's content dir, never
 * routes, and the route-to-file inverse is not derivable by convention here (16
 * docs override `slug:`, every blog file is `YYYY-MM-DD-*`). They come from the
 * `sourceFile` the manifest builder already records beside every route.
 */
export function contentExcludeOption(surface, coverage = currentLocaleCoverage()) {
  if (!SURFACES.includes(surface)) throw new Error(`Unknown content surface '${surface}'`);
  if (coverage.unrestricted) return undefined;

  const always = surface === 'pages' ? alwaysExcludedGlobs() : [];
  const exclude = [
    ...GLOB_EXCLUDE_DEFAULT,
    ...always,
    ...coverage.uncovered[surface].map(assertGlobSafe),
  ];
  return { exclude };
}

/**
 * `legal/**` (tiers.json `alwaysExcluded`): English-only in every locale, since
 * translated legal text creates real exposure and has zero SEO value.
 *
 * Uncovered legal pages would already be excluded by the manifest arithmetic
 * above, since no route set declares them. This states the rule anyway, so a
 * manifest bug cannot publish machine-translated legal terms.
 */
export function alwaysExcludedGlobs(root = ROOT) {
  return loadTiers(root).alwaysExcluded?.globs ?? [];
}

/* ------------------------------------------------------------ sidebar (task a) */

/**
 * Filter a sidebars config down to the docs this locale actually builds.
 *
 * `plugin-content-docs` throws "These sidebar document ids do not exist" during
 * content load, BEFORE any link checking, so an unfiltered sidebar kills every
 * non-full locale build outright. `loadSidebarsFileUnsafe` returns the module as
 * it stands (a function export is not supported), which is why this runs at
 * module-evaluation time in `sidebars.ts` instead of being a lazy callback.
 *
 * Returns the SAME OBJECT REFERENCE when unrestricted. English output is
 * therefore identical by construction rather than by a deep-equality argument.
 *
 * @template T
 * @param {T} sidebars
 * @param {ReturnType<typeof localeCoverage>} coverage
 * @returns {T}
 */
export function filterSidebars(sidebars, coverage = currentLocaleCoverage()) {
  if (coverage.unrestricted) return sidebars;
  const out = {};
  for (const [name, items] of Object.entries(sidebars)) {
    const kept = filterSidebarItems(items, coverage.docIds);
    // A sidebar with no items is dropped rather than emitted empty: docs that
    // would have used it simply render without a sidebar, whereas an empty
    // CATEGORY throws.
    if (kept.length) out[name] = kept;
  }
  return /** @type {T} */ (out);
}

function filterSidebarItems(items, covered) {
  if (!Array.isArray(items)) return [];
  const out = [];
  for (const item of items) {
    const kept = filterSidebarItem(item, covered);
    if (kept !== null) out.push(kept);
  }
  return out;
}

function filterSidebarItem(item, covered) {
  if (typeof item === 'string') return covered.has(item) ? item : null;
  if (!item || typeof item !== 'object') return item;

  switch (item.type) {
    case 'doc':
    case 'ref':
      return covered.has(item.id) ? item : null;

    case 'autogenerated':
      // The generator throws "Can't find any doc with directory name X" when a
      // dir yields nothing, so a dir whose every doc was excluded has to go.
      // Dirs that keep at least one doc need no further pruning: autogeneration
      // only ever sees the files that survived the plugin `exclude`.
      return hasCoveredDocUnder(covered, item.dirName) ? item : null;

    case 'category': {
      // Category link first: a category whose landing page is untranslated is
      // dropped whole, rather than left pointing at a route this locale does
      // not build (onBrokenLinks: 'throw').
      if (item.link?.type === 'doc' && !covered.has(item.link.id)) return null;
      const items = filterSidebarItems(item.items, covered);
      // Empty items are fine when the category has a link: postProcessSidebarItem
      // renders it as a plain doc item. Without a link it throws.
      if (!items.length && !item.link) return null;
      return items.length === (item.items?.length ?? 0) ? item : { ...item, items };
    }

    default:
      // 'link' and 'html' items carry an href or raw markup rather than a doc id.
      // This sidebar has none; if one is added pointing at an internal route, it
      // needs its own coverage check here or it will fail the locale build.
      return item;
  }
}

function hasCoveredDocUnder(covered, dirName) {
  if (!dirName || dirName === '.') return covered.size > 0;
  const prefix = `${dirName.replace(/\/+$/, '')}/`;
  for (const id of covered) if (id.startsWith(prefix)) return true;
  return false;
}
